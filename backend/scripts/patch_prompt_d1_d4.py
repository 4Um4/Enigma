# backend/scripts/patch_prompt_d1_d4.py
# Идемпотентный патчер chronicle_decompose_system.txt — добавляет D1-D4
import io, sys, pathlib

PROMPT_PATH = pathlib.Path("backend/prompts/chronicle_decompose_system.txt")
MARKER = "D1. age_anchors ↔ items"  # маркер уже применённого патча
ANCHOR_LINE = "ФРАГМЕНТ АВТОРА (в user-сообщении) — разбираешь его. Предыдущий контекст НЕ выдумываешь."

D_BLOCK = """\
D1. age_anchors ↔ items (anti-drop)
age_anchors[] — это КОНТРАКТ, а не декорация. Каждый ненулевой якорь
из age_anchors ДОЛЖЕН быть отражён хотя бы в одном item:
  - years_ago=N     → хотя бы один EVENT с years_ago=N в draft_payload,
                      ИЛИ RELATIONSHIP, в evidence/summary которого
                      прямо упомянута привязка «N лет назад»
  - duration_years=N → хотя бы один EVENT с duration_years=N в draft_payload
  - at_age=N        → хотя бы один EVENT с age=N в draft_payload
  - since_age=N     → хотя бы один EVENT с age=N (начала периода) в draft_payload

Если возрастной якорь извлечён, а в items он не нашёл отражения —
это означает, что ты ДРОПНУЛ семантическую единицу. Вернись к
фрагменту и найди событие/отношение, к которому этот якорь
привязан в тексте.

АНТИПРИМЕР D1 (повисший age_anchor):
  Фрагмент: «Хороший его друг Торнин, который напоминает ему старого
            друга, умершего 70 лет назад.»
  age_anchors: [70]
  items: [ { kind: RELATIONSHIP, target_hint: "Торнин" } ]
  ← НЕВЕРНО: years_ago=70 повис, не отражён ни в одном item.
  ВЕРНО: добавить второй item
  { kind: EVENT, summary: "Умер старый друг", years_ago: 70 }

D2. Консолидация родственных TRAIT_SEED
Несколько предложений/клауз, выражающих ОДНУ смысловую ось
(«молчание как разрешение», «отказ от объяснения мотивов»,
«подчинение указанию без вопросов»), ДОЛЖНЫ быть объединены в ОДИН
TRAIT_SEED с синтезированным trait-лейблом, а не порождать N
почти-синонимичных трейтов.

Признаки родственных клауз:
  - общий корневой концепт (молчание / подчинение / отказ-объяснять)
  - один и тот же субъект-носитель (тот же персонаж)
  - evidence из одной смысловой цепочки текста

АНТИПРИМЕР D2 (избыточное дробление):
  items: [
    { kind: TRAIT_SEED, trait: "не объясняет себе причины поступков" }
    { kind: TRAIT_SEED, trait: "пользуется разрешением для молчания" }
    { kind: TRAIT_SEED, trait: "не надо объяснять себе, почему ты делаешь то, что делаешь" }
  ]
  ← НЕВЕРНО: три трейта выражают одну ось. Объединить в один:
  { kind: TRAIT_SEED,
    trait: "практикует молчание без объяснения мотивов",
    evidence: "<цитата, охватывающая все три клаузы>" }

D3. trait ↔ evidence (semantic bind)
trait ДОЛЖЕН быть непосредственно выводим из evidence своего
фрагмента. Если evidence не содержит слова или концепта, давшего
имя trait'у — это галлюцинация или перенос из другого фрагмента.

Проверка: прочти evidence. Найди в нём слово/фразу, которая
определяет trait. Если не нашёл — НЕ эмитить TRAIT_SEED.
Также: НЕ переноси trait'ы из других фрагментов. Каждый TRAIT_SEED
должен быть выведен из текста СВОЕГО фрагмента.

АНТИПРИМЕР D3 (перенос trait'а):
  Фрагмент 2:  «Увлечён по-настоящему только своей работой и выпивкой.»
  Фрагмент 15: «…стратегия выживания гнома, который живёт в этом
                городе 57 лет»
  items[15]: [ { kind: TRAIT_SEED, trait: "увлечён работой",
                 evidence: "<цитата из фрагмента 15>" } ]
  ← НЕВЕРНО: trait «увлечён работой» не выводим из evidence
  фрагмента 15; он был канонизирован в фрагменте 2.
  В п.15 этот TRAIT_SEED эмитировать НЕ НАДО.

D4. Факт ≠ TRAIT_SEED
Демографические и биографические факты — это НЕ TRAIT_SEED:
  - раса / вид («гном», «эльф»)
  - профессия («кузнец», «стражник»)
  - место жительства («живёт в этом городе»)
  - возраст / давность проживания

Такие факты уходят в:
  - PORTRET.statement (если это характеристика-описание)
  - EVENT (если это событие, напр. «стал кузнецом» — но только
            если в тексте действительно есть этот глагол)
  - KNOWLEDGE_LINK (если это знание о мире/о себе)

TRAIT_SEED — это УСТОЙЧИВАЯ ЧЕРТА ХАРАКТЕРА/ПОВЕДЕНИЯ:
«привык держать всё в себе», «не объясняет мотивов», «боится
толпы» — то, что можно наблюдать в паттернах поведения.

АНТИПРИМЕР D4:
  { kind: TRAIT_SEED, trait: "гном",
    evidence: "А гному, который 20 лет назад потерял жену..." }
  ← НЕВЕРНО: «гном» — это раса, а не черта характера.
  Либо PORTRET (если важно подчеркнуть идентичность),
  либо вообще не эмитировать как отдельный item.

"""

def main():
    if not PROMPT_PATH.exists():
        print(f"ERROR: prompt file not found: {PROMPT_PATH}", file=sys.stderr)
        sys.exit(2)

    text = PROMPT_PATH.read_text(encoding="utf-8")

    if MARKER in text:
        print(f"[skip] D1-D4 уже присутствуют в {PROMPT_PATH}")
        return

    if ANCHOR_LINE not in text:
        print(f"ERROR: anchor line not found in prompt:\n  {ANCHOR_LINE}", file=sys.stderr)
        sys.exit(3)

    # Вставляем блок ПЕРЕД последней строкой-маркером
    new_text = text.replace(ANCHOR_LINE, D_BLOCK + "\n" + ANCHOR_LINE)

    PROMPT_PATH.write_text(new_text, encoding="utf-8")
    print(f"[ok] D1-D4 inserted into {PROMPT_PATH}")
    print(f"     size: {len(text)} -> {len(new_text)} bytes")

if __name__ == "__main__":
    main()