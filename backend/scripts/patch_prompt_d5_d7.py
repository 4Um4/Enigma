# backend/scripts/patch_prompt_d5_d7.py
# Идемпотентное расширение D-блока: D5, D6, D7
import sys, pathlib

PROMPT_PATH = pathlib.Path("backend/prompts/chronicle_decompose_system.txt")
MARKER = "D5. PORTRET приоритет"

D_BLOCK = """\
D5. PORTRET приоритет над TRAIT_SEED для характерологических описаний

Если утверждение описывает «какой персонаж» / «как его оценивают» /
«какую роль играет» — это PORTRET, не TRAIT_SEED.

Признаки PORTRET-утверждения:
  - оценка/мнение («не опасен», «не амбициозен», «удобный»)
  - метафора-описание («мебель города», «инструмент»)
  - социальная роль («кузнец», «информатор», «старейшина»)
  - демографический факт («гном», «живёт здесь 57 лет»)
  - мотив-объяснение («не из хитрости, из привычки»)
  - утверждение о балансе/стратегии («стратегия выживания»)

PORTRET.statement = исходная фраза целиком (дословно).
PORTRET.traits = массив слов-характеристик (0..5); может быть ПУСТЫМ,
если в тексте нет полноценного поведенческого паттерна.

TRAIT_SEED — это УСТОЙЧИВАЯ ЧЕРТА ПОВЕДЕНИЯ, наблюдаемая в паттернах
действий: «привык держать всё в себе», «не объясняет мотивов»,
«избегает толпы». Это можно ПОКАЗАТЬ в действии, а не просто
УТВЕРДИТЬ.

АНТИПРИМЕР D5 (характерология как TRAIT_SEED):
  items: [
    { kind: TRAIT_SEED, trait: "не опасен", evidence: "..." },
    { kind: TRAIT_SEED, trait: "не амбициозен", evidence: "..." },
    { kind: TRAIT_SEED, trait: "мебель города", evidence: "..." },
    { kind: TRAIT_SEED, trait: "из привычки", evidence: "..." }
  ]
  ← НЕВЕРНО: это всё STATE-описания, не черты поведения.
  ВЕРНО: собрать их в ОДИН PORTRET с statement = фраза целиком,
  traits: [] (пусто, т.к. паттернов поведения тут нет).

D6. ЛИМИТ НА ФРАГМЕНТ (hard cap)

Максимум 6 items на фрагмент. Это уже правило 7, но повторяем явно:
если ты эмитируешь >6 items — ты ПЕРЕДРОБИЛ.

Что делать при >6:
  - консолидируй родственные TRAIT_SEED по D2
  - уходи в PORTRET для характерологии по D5 (statement целиком, traits=[])
  - объединяй несколько EVENT из одной сцены в один
  - проверяй D7 (правила-из-опыта → BELIEF_SEED) и
    RELATIONSHIP с организациями/группами

Если после консолидации всё ещё >6 — выбери 6 самых причинно-значимых,
остальные опусти (лучше меньше, чем мусор).

D7. BELIEF_SEED для правил-из-опыта

Если утверждение формулирует ПРАВИЛО О МИРЕ, выведенное из опыта
(«кто молчит — тот первый, кого убирают»), — это BELIEF_SEED с
belief_type=danger.

Признаки BELIEF_SEED-утверждения:
  - обобщение о поведении людей/мира
  - правило выживания / правило безопасности
  - вывод из долгого опыта, не привязанный к конкретному событию

В существующем реестре только два значения: danger (мир опасен)
и player_hostile (игрок враждебен). Если утверждение не подходит
ни под одно — НЕ создавай BELIEF_SEED (но и не эмитируй как
TRAIT_SEED — это PORTRET.statement).

АНТИПРИМЕР D7 (правило-из-опыта как TRAIT_SEED):
  items: [
    { kind: TRAIT_SEED, trait: "молчит опасно", evidence: "..." }
  ]
  ← НЕВЕРНО: «кто молчит — того убирают» — это правило мира,
  не черта характера Орма.
  ВЕРНО: { kind: BELIEF_SEED,
           statement: "кто молчит — тот первый, кого убирают",
           belief_type: "danger" }

D8. RELATIONSHIP с организациями/группами

Если текст описывает устойчивое отношение персонажа с ГИЛЬДИЕЙ,
ПРАВИТЕЛЬСТВОМ, КЛАНОМ, ГРУППОЙ — это RELATIONSHIP с
target_hint = имя организации. Скалярный target_hint=Организация
легален (не только индивидуальные имена).

Пример: «Гильдия терпит его, потому что он их кузнец, их информатор»
→ RELATIONSHIP { target_hint: "Гильдия воров",
                  nature: "взаимовыгодный",
                  summary: "Гильдия терпит его, потому что он их
                          кузнец, информатор, удобный гном" }

АНТИПРИМЕР D8 (роль перед TRAIT_SEED вместо RELATIONSHIP):
  items: [
    { kind: TRAIT_SEED, trait: "кузнец гильдии", evidence: "..." },
    { kind: TRAIT_SEED, trait: "информатор гильдии", evidence: "..." }
  ]
  ← НЕВЕРНО: это роли в организации, не черты характера.
  ВЕРНО: один RELATIONSHIP с target_hint="Гильдия воров",
  summary содержит обе роли.

"""

def main():
    if not PROMPT_PATH.exists():
        print(f"ERROR: {PROMPT_PATH} not found", file=sys.stderr)
        sys.exit(2)

    text = PROMPT_PATH.read_text(encoding="utf-8")

    if MARKER in text:
        print(f"[skip] D5-D7 уже присутствуют")
        return

    # Вставляем ПЕРЕД D4 (т.к. D5 ссылается на D4, D6 ссылается на D5/D2)
    anchor = "D4. Факт ≠ TRAIT_SEED"
    if anchor not in text:
        print(f"ERROR: anchor '{anchor}' not found", file=sys.stderr)
        sys.exit(3)

    new_text = text.replace(anchor, D_BLOCK + "\n" + anchor)
    PROMPT_PATH.write_text(new_text, encoding="utf-8")
    print(f"[ok] D5-D8 inserted before D4")
    print(f"     size: {len(text)} -> {len(new_text)} bytes")

if __name__ == "__main__":
    main()