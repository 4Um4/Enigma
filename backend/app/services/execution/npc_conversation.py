class NpcConversation:
    """
    Локальный генератор реплик для ambient-диалогов.
    Не вызывает LLM, использует заранее заготовленные фразы.
    Имплементирует интерфейс TaskExecutor.
    """

    def execute(self, task: QueuedTask) -> Iterable[Artifact]:
        if not isinstance(task.payload, DialogueRequest):
            logger.error(f"[NPC_CONV] Invalid payload type: {type(task.payload)}")
            yield Artifact(
                task_id=task.task_id,
                success=False,
                result_type="error",
                data={},
                error_message="Invalid payload for NpcConversation",
            )
            return

        req = task.payload
        logger.debug(f"[NPC_CONV] Generating ambient line for {task.owner_id} -> {req.target_id}")

        text = random.choice(_AMBIENT_PHRASES)
        
        yield Artifact(
            task_id=task.task_id,
            success=True,
            result_type="dialogue_line",
            data={
                "speaker_id": task.owner_id,
                "target_id": req.target_id,
                "text": text,
                "exposure": req.exposure.semantic,
                "topic": req.topic,
                "emotional_state": req.emotional_state,
            },
        )