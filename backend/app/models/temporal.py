"""
Файл: backend/app/models/temporal.py
Назначение: Единый контракт временного состояния мира (тик, день, расписание decay).
Зависимости: Нет (чистый domain)
Основные сущности: TemporalContext

Принципы:
  - TemporalContext — это неизменяемый снимок времени, который передаётся всем подсистемам в каждом тикe.
  - Он содержит текущий тик, игровой день, часы, а также информацию о том, нужно ли запускать decay для памяти NPC.
  - Все подсистемы (NPC AI, EventBus, MemoryEngine) используют TemporalContext для синхронизации своих действий и принятия решений.
  - TemporalContext НЕ хранится в NPC или других сущностях. Это глобальный контекст, который вычисляется в начале каждого world_tick() и передаётся вниз по цепочке вызовов.
  - Это позволяет централизованно управлять временем и гарантирует, что все части системы работают с одной и той же временной информацией, что критично для консистентности поведения NPC и правильного запуска событий.
  - В будущем TemporalContext может быть расширен дополнительными полями, такими как "is_night_time" или "is_festival_day", чтобы ещё больше обогатить контекст для принятия решений NPC.

  - Добавить "is_night_time" для влияния на поведение NPC (например, более агрессивные монстры ночью).
  - Ввести "is_festival_day" для создания особых событий и поведения NPC в праздничные дни.
  - Рассмотреть возможность добавления "season" для влияния на доступные ресурсы и поведение NPC (например, зима → меньше еды, более агрессивные животные).
  - Логирование TemporalContext в начале каждого world_tick() для анализа и отладки поведения NPC в зависимости от времени.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class TemporalContext:
    """
    Снимок временного состояния мира на текущий тик.
    Единая точка правды для всех подсистем: сколько тиков прошло,
    какой игровой день, нужно ли запускать decay.
    """

    current_tick: int
    game_day: int  # current_tick // TICKS_PER_DAY
    game_hour: int  # current_tick % TICKS_PER_DAY
    is_new_day: bool  # game_hour == 0 (начало нового игрового дня)
    ticks_since_last_decay: int  # тиков с последнего memory decay
    should_run_memory_decay: bool  # ticks_since_last_decay >= DECAY_EVERY
